/**
 * Retorna los Hospitales de Shock Trauma 24h ordenados dinámicamente por distancia GPS
 */
export function getNearestEmergencyHospitals(
  userLat: number,
  userLng: number,
  limit = 8
): HealthFacility[] {
  return HEALTH_FACILITIES_DATABASE
    .filter((f) => f.hasEmergency24h)
    .map((facility) => {
      const distKm = calculateDistanceKm(userLat, userLng, facility.lat, facility.lng);
      const eta = estimateETA(distKm);
      return {
        ...facility,
        distanceKm: distKm,
        distanceFormatted: formatDistance(distKm),
        etaWalking: eta.walking,
        etaDriving: eta.driving,
      };
    })
    .sort((a, b) => (a.distanceKm || 0) - (b.distanceKm || 0))
    .slice(0, limit);
}

