/**
 * Búsqueda de centros en la base de datos por texto (nombre, distrito, especialidad, zona)
 */
export function searchFacilities(
  query: string,
  userLat: number,
  userLng: number
): HealthFacility[] {
  const q = query.toLowerCase().trim();
  if (!q) {
    return getNearestHealthCenters(userLat, userLng);
  }

  return HEALTH_FACILITIES_DATABASE
    .filter(
      (f) =>
        f.name.toLowerCase().includes(q) ||
        f.district.toLowerCase().includes(q) ||
        f.zone.toLowerCase().includes(q) ||
        f.specialty.toLowerCase().includes(q) ||
        f.type.toLowerCase().includes(q)
    )
    .map((facility) => {
      const distKm = calculateDistanceKm(userLat, userLng, facility.lat, facility.lng);
      const eta = estimateETA(distKm);
      return {
        ...facility,
        distanceKm: distKm,
        distanceFormatted: formatDistance(distKm),
        etaWalking: eta.walking,
        etaDriving: eta.driving,
      };
    })
    .sort((a, b) => (a.distanceKm || 0) - (b.distanceKm || 0));
}
